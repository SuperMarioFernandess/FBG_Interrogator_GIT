def threshold_spectrum_hint(max_adc: int | None, threshold: int | None) -> str:
    """Подсказка порога по последнему спектру, если он уже есть."""
    if max_adc is None:
        return THRESHOLD_SPECTRUM_UNKNOWN
    if threshold is not None and threshold > max_adc:
        return (
            f"Максимум АЦП последнего спектра: {max_adc}. Порог {threshold} выше максимума — "
            "при таком спектре прибор найдёт 0 пиков."
        )
    return (
        f"Максимум АЦП последнего спектра: {max_adc}. "
        "Ручной порог выше этого максимума даст 0 найденных пиков."
    )


def gain_spectrum_hint(saturated_points: int | None) -> str:
    """Подсказка усиления по насыщению последнего спектра."""
    if saturated_points is None:
        return GAIN_SPECTRUM_UNKNOWN
    if saturated_points > 0:
        return (
            f"В последнем спектре насыщенных точек: {saturated_points}. "
            "Насыщение искажает форму пиков и их положения; уменьшите усиление."
        )
    return (
        "В последнем спектре насыщенных точек нет. На стенде автоусиление выбирало "
        "уровни 3–4 и насыщало АЦП, поэтому после смены усиления проверяйте спектр снова."
    )


