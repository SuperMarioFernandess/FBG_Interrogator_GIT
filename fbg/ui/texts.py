def hex_truncated_suffix(total: int) -> str:
    """Приписка к укороченной строке hex в ячейке таблицы.

    Обрезается **только показ**: в файле журнала и в экспорте байты лежат
    целиком и никогда не обрезаются (правило KB_05 №3). Ответ `30 03` — это
    20430 байт, то есть 61 КБ hex в одной ячейке; таблица на таком встаёт,
    а прочитать его глазами всё равно нельзя.
    """
    return f" … всего {total} Б, целиком — в файле и в экспорте"


