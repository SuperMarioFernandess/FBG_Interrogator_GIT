class Tone(StrEnum):
    """Как выглядит значение: цвет индикатора, а не смысл.

    `NEUTRAL` и `WARN` различаются намеренно. `Degraded` и `Reconnecting` —
    не отказ, а рабочее состояние автомата: связь потеряна, но приложение
    её восстанавливает. Выглядеть так же, как `Disconnected`, они не должны,
    иначе оператор за стендом решит, что нажатие «Подключить» не сработало.
    """

    NEUTRAL = "neutral"
    """Ничего не происходит и не должно: связи нет, потому что не подключались."""

    BUSY = "busy"
    """Идёт обмен, результат ещё не известен."""

    OK = "ok"
    """Связь есть."""

    WARN = "warn"
    """Связь нарушена, идёт восстановление. Не ошибка."""

    ERROR = "error"
    """Отказ, требующий человека."""


