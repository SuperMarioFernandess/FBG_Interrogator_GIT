"""Сетевые настройки как данные: куда слать байты и куда их принимать.

Разделение с `DeviceProfile` намеренное (решение Р19 в KB_03): профиль отвечает
на вопрос «как разложены байты», `Endpoint` — «куда их слать». Смена IP прибора
не меняет раскладку кадра, а смена гипотезы о единицах частоты не меняет адрес.

Модуль не импортирует `socket`: это структура конфигурации, а не поведение.
Значения по умолчанию — заводские, ✅ проверены на приборе (KB_01, раздел «Сеть»).
"""

from dataclasses import dataclass

#: Максимальный номер порта.
MAX_PORT = 65535


@dataclass(frozen=True)
class Endpoint:
    """Адреса и параметры UDP-обмена с прибором.

    Прибор отвечает на **жёстко прописанный** Destination IP:Port, а не на
    source-порт запроса (KB_01). Отсюда два следствия, зашитые в умолчания:
    `local_port` фиксирован (8001, а не эфемерный), и команды обязаны уходить
    из того же сокета, который слушает этот порт.

    🔴 Скрининг добавил третье следствие: адрес назначения у прибора —
    **широковещательный**. Все 4937 ответов ушли на `255.255.255.255:8001`
    с порта 4567, а не на IP компьютера. Поэтому `local_ip` обязан оставаться
    `0.0.0.0` — см. комментарий к полю.

    Не все поля читает транспорт. `read_timeout_s`, `write_timeout_s` и
    `retries` — параметры уровня `session` (KB_03: 500 мс на чтение, 1000 мс
    на запись, 3 попытки). Они лежат здесь, потому что это сетевые настройки,
    которые пользователь правит в одном диалоге, а не потому что их применяет
    транспорт. Период опроса приёмного сокета — отдельное поле
    `rx_poll_timeout_s`: путать его с таймаутом ожидания ответа нельзя, иначе
    `close` начнёт ждать полсекунды.
    """

    device_ip: str = "192.168.0.19"
    device_port: int = 4567

    #: 🔴 Обязано оставаться `0.0.0.0` (решение Р29, KB_03).
    #:
    #: Прибор отвечает **широковещательно** на `255.255.255.255:8001`
    #: (✅ скрининг 27.08.2026, все 4937 ответов). Bind на конкретный адрес
    #: интерфейса — например, на `192.168.0.14` — широковещательные датаграммы
    #: на Windows **не получит**: приложение будет молчать при полностью
    #: исправной связи и исправном приборе. Это самый дорогой класс отказа,
    #: потому что выглядит он как «сеть не работает».
    #:
    #: Значение по умолчанию было верным и до скрининга, но по другой причине —
    #: теперь это требование, а не удобное совпадение.
    local_ip: str = "0.0.0.0"
    local_port: int = 8001

    #: Запрос `SO_RCVBUF`. При 2000 датаграммах/с поток равен 0.99 МБ/с (KB_01),
    #: то есть 8 МБ буфера покрывают около 8 секунд полного затыка приёмника.
    #: Ядро вправе выдать меньше — фактический размер читает `UdpTransport.rcvbuf_actual`.
    rcvbuf_bytes: int = 8 * 1024 * 1024

    #: Таймаут ожидания ответа на команду. Читает `session`, не транспорт.
    read_timeout_s: float = 0.5

    #: Таймаут отправки команды. Читает `session`, не транспорт.
    write_timeout_s: float = 1.0

    #: Число попыток повтора команды. Читает `session`, не транспорт.
    retries: int = 3

    #: Период опроса приёмного сокета. Определяет, как быстро останавливается
    #: приёмный поток: `close` ждёт не дольше этого времени плюс обработка
    #: последней датаграммы. Значение не влияет ни на темп приёма, ни на потери:
    #: при 2 кГц `recvfrom` возвращается сразу и таймаут не наступает вовсе.
    rx_poll_timeout_s: float = 0.05

    #: Глубина внутренней очереди транспорта в датаграммах. 4096 кадров по
    #: 494 байта — около 2 МБ и 2 секунды потока при 2 кГц. Согласовано
    #: с глубиной очереди телеметрии из KB_03.
    rx_queue_capacity: int = 4096

    #: Сверять ли source-порт принятой датаграммы с `device_port`.
    #:
    #: Вопрос N16 закрыт: ✅ прибор шлёт с порта 4567, и включённый фильтр
    #: больше не рискует отбросить весь поток. Тем не менее по умолчанию он
    #: остаётся **выключенным**, и это осознанное решение, а не забытая строка.
    #:
    #: Довод в пользу выключения — асимметрия цены ошибки. Фильтр по порту
    #: не отсекает ничего, чего уже не отсекает обязательный фильтр по IP:
    #: датаграмма с IP прибора и другого порта пришла бы всё равно от прибора.
    #: Зато при смене source-порта — другая прошивка, замена прибора, NAT
    #: на пути — включённый фильтр даёт полное молчание приложения при
    #: исправной связи, ровно тот же класс отказа, из-за которого `local_ip`
    #: обязан быть `0.0.0.0`.
    #:
    #: Поле оставлено, потому что теперь его **можно** включать осмысленно:
    #: например, при отладке в подсети, где широковещательный трафик прибора
    #: видят все узлы и рядом работает второй экземпляр приложения.
    strict_source_port: bool = False

    def __post_init__(self) -> None:
        """Проверяет согласованность настроек.

        Некорректный `Endpoint` собирает программа, а не сеть, поэтому здесь
        `ValueError`, а не `Result` (KB_05, таблица «Ошибки»).
        """
        if not self.device_ip:
            raise ValueError("device_ip не может быть пустым")
        if not self.local_ip:
            raise ValueError("local_ip не может быть пустым; для «любого адреса» это 0.0.0.0")
        if not 1 <= self.device_port <= MAX_PORT:
            raise ValueError(f"device_port={self.device_port} вне диапазона 1…{MAX_PORT}")
        # 0 допустим: эфемерный порт нужен тестам, чтобы не занимать 8001.
        if not 0 <= self.local_port <= MAX_PORT:
            raise ValueError(f"local_port={self.local_port} вне диапазона 0…{MAX_PORT}")
        if self.rcvbuf_bytes < 1:
            raise ValueError(f"rcvbuf_bytes={self.rcvbuf_bytes} должен быть ≥ 1")
        for name, value in (
            ("read_timeout_s", self.read_timeout_s),
            ("write_timeout_s", self.write_timeout_s),
            ("rx_poll_timeout_s", self.rx_poll_timeout_s),
        ):
            if value <= 0:
                raise ValueError(f"{name}={value} должен быть положительным")
        if self.retries < 0:
            raise ValueError(f"retries={self.retries} не может быть отрицательным")
        if self.rx_queue_capacity < 1:
            raise ValueError(f"rx_queue_capacity={self.rx_queue_capacity} должна быть ≥ 1")

    @property
    def device_address(self) -> tuple[str, int]:
        """Адрес прибора для `sendto`."""
        return self.device_ip, self.device_port

    @property
    def bind_address(self) -> tuple[str, int]:
        """Адрес, на который биндится приёмный сокет."""
        return self.local_ip, self.local_port
